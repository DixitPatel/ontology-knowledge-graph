-- =====================================================
-- Load the Sephora skincare catalog (RDF -> nodes.csv/edges.csv, see
-- scripts/sephora_to_rdf.py) into SKINCARE_KG.KG via stage + MERGE.
-- Run after: snow stage copy docs/kb-data/nodes.csv @KG_STAGE -c kg
--            snow stage copy docs/kb-data/edges.csv @KG_STAGE -c kg
-- Idempotent: EDGE_ID/NODE_ID are stable, so re-running changes no counts.
-- Rollback: DELETE FROM KG_EDGE WHERE SOURCE='SEPHORA_KAGGLE_2023';
--           DELETE FROM KG_NODE WHERE SOURCE='SEPHORA_KAGGLE_2023';
-- =====================================================
USE SCHEMA SKINCARE_KG.KG;

CREATE STAGE IF NOT EXISTS KG_STAGE
  FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"');

CREATE OR REPLACE TEMP TABLE NODE_STG (
  NODE_ID STRING, NODE_TYPE STRING, NAME STRING, PROPS STRING, SOURCE STRING
);
CREATE OR REPLACE TEMP TABLE EDGE_STG (
  EDGE_ID STRING, SRC_ID STRING, DST_ID STRING, EDGE_TYPE STRING,
  WEIGHT FLOAT, PROPS STRING, SOURCE STRING, STATUS STRING
);

COPY INTO NODE_STG (NODE_ID, NODE_TYPE, NAME, PROPS, SOURCE)
  FROM @KG_STAGE/nodes.csv
  FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"')
  ON_ERROR = ABORT_STATEMENT;

COPY INTO EDGE_STG (EDGE_ID, SRC_ID, DST_ID, EDGE_TYPE, WEIGHT, PROPS, SOURCE, STATUS)
  FROM @KG_STAGE/edges.csv
  FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"')
  ON_ERROR = ABORT_STATEMENT;

SELECT 'staged' AS step, (SELECT COUNT(*) FROM NODE_STG) AS node_rows, (SELECT COUNT(*) FROM EDGE_STG) AS edge_rows;

MERGE INTO KG_NODE t USING NODE_STG s ON t.NODE_ID = s.NODE_ID
  WHEN MATCHED THEN UPDATE SET NAME = s.NAME, PROPS = PARSE_JSON(s.PROPS), TS_INGESTED = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (NODE_ID, NODE_TYPE, NAME, PROPS, SOURCE)
    VALUES (s.NODE_ID, s.NODE_TYPE, s.NAME, PARSE_JSON(s.PROPS), s.SOURCE);

MERGE INTO KG_EDGE t USING EDGE_STG s ON t.EDGE_ID = s.EDGE_ID
  WHEN MATCHED THEN UPDATE SET PROPS = PARSE_JSON(s.PROPS), TS_INGESTED = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (EDGE_ID, SRC_ID, DST_ID, EDGE_TYPE, WEIGHT, PROPS, SOURCE, STATUS)
    VALUES (s.EDGE_ID, s.SRC_ID, s.DST_ID, s.EDGE_TYPE, s.WEIGHT, PARSE_JSON(s.PROPS), s.SOURCE, s.STATUS);

SELECT SOURCE, NODE_TYPE, COUNT(*) FROM KG_NODE GROUP BY 1, 2 ORDER BY 1, 2;
SELECT SOURCE, EDGE_TYPE, COUNT(*) FROM KG_EDGE GROUP BY 1, 2 ORDER BY 1, 2;
